static constexpr const char *kRcaHid8 = "AD7B90E1EB12A0F9";

class CliVerifyHid8Test : public ::testing::Test {
protected:
    fs::path dir_;
    fs::path cert_;

    void SetUp() override {
        dir_ = fs::temp_directory_path() / ("v2xpki_cli_test." + std::to_string(::getpid()));
        fs::create_directories(dir_);
        cert_ = dir_ / "rca.cert";
        std::ofstream ofs(cert_.string(), std::ios::binary);
        ofs.write(reinterpret_cast<const char *>(kCastellRca), sizeof(kCastellRca));
    }

    void TearDown() override { fs::remove_all(dir_); }

    // Runs the CLI, returns its exit status and captures stdout+stderr.
    int run(const std::string &args, std::string *out = nullptr) {
        std::string cmd = std::string(V2XPKI_CLI_BINARY) + " " + args + " 2>&1";
        FILE *pipe = popen(cmd.c_str(), "r");
        if (!pipe) return -1;
        std::string buf;
        char chunk[256];
        while (fgets(chunk, sizeof(chunk), pipe))
            buf += chunk;
        int rc = pclose(pipe);
        if (out) *out = buf;
        return WIFEXITED(rc) ? WEXITSTATUS(rc) : -1;
    }
};

TEST_F(CliVerifyHid8Test, ComputesHid8WithoutPin) {
    std::string out;
    EXPECT_EQ(run("verify-hid8 --cert-path " + cert_.string(), &out), 0);
    EXPECT_NE(out.find(kRcaHid8), std::string::npos);
}

TEST_F(CliVerifyHid8Test, MatchingPinSucceeds) {
    std::string out;
    EXPECT_EQ(run("verify-hid8 --cert-path " + cert_.string() + " --hid8 " + kRcaHid8, &out), 0);
    EXPECT_NE(out.find("Match:  yes"), std::string::npos);
}

TEST_F(CliVerifyHid8Test, LowercasePinSucceeds) {
    EXPECT_EQ(run("verify-hid8 --cert-path " + cert_.string() + " --hid8 ad7b90e1eb12a0f9"), 0);
}

TEST_F(CliVerifyHid8Test, MismatchedPinFails) {
    std::string out;
    int rc = run("verify-hid8 --cert-path " + cert_.string() + " --hid8 DEADBEEFDEADBEEF", &out);
    EXPECT_EQ(rc, 1);
    EXPECT_NE(out.find("mismatch"), std::string::npos);
}

TEST_F(CliVerifyHid8Test, MismatchedPinFailsJson) {
    std::string out;
    int rc = run("verify-hid8 --json --cert-path " + cert_.string() + " --hid8 DEADBEEFDEADBEEF",
                 &out);
    EXPECT_EQ(rc, 1);
    EXPECT_NE(out.find("\"match\":false"), std::string::npos);
}

TEST_F(CliVerifyHid8Test, UnparseableCertFails) {
    auto junk = dir_ / "junk.cert";
    {
        std::ofstream ofs(junk.string(), std::ios::binary);
        ofs << "not a COER certificate";
    }
    EXPECT_EQ(run("verify-hid8 --cert-path " + junk.string()), 1);
}

TEST_F(CliVerifyHid8Test, MissingCertPathFails) { EXPECT_EQ(run("verify-hid8"), 1); }
